def render_page(title: str, description: str, body: str, *, depth: int, generated_at: str) -> str:
    root_path = "../" * depth
    css_path = root_path
    head = PAGE_HEAD.format(title=esc(title), description=esc(description), css_path=css_path, root_path=root_path)
    foot = PAGE_FOOT.format(root_path=root_path, generated_at=esc(generated_at))
    return head + body + foot


def render_badge(status_key: str) -> str:
    entry = STATUS_VOCAB.get(status_key, STATUS_VOCAB["proof-pending"])
    return f'<span class="evidence-badge {entry["badge"]}">{esc(entry["label"])}</span>'


def render_freshness_badge(status: str) -> str:
    color = FRESHNESS_LABEL.get(status, "gray")
    return f'<span class="evidence-badge {color}">{esc(status)}</span>'


def render_index(matrix: dict[str, Any]) -> str:
    caps = matrix["capabilities"]
    by_category: dict[str, list[dict[str, Any]]] = {}
    for cap in caps:
        by_category.setdefault(cap["category"], []).append(cap)

    rows = []
    for cap in caps:
        status = capability_status(cap)
        sdk_summary = " ".join(
            f'<span class="sdk-chip {sdk_status_badge(cap["sdks"].get(sdk, {}).get("status"))}" title="{esc(sdk)}">{esc(sdk[:2].upper())}</span>'
            for sdk in ("js", "dotnet", "python")
        )
        sample_count = len(cap.get("samples", []))
        gap_count = cap.get("openIssues", {}).get("count", 0)
        rows.append(
            "<tr data-key=\"{key}\" data-category=\"{cat}\" data-edition=\"{ed}\" data-status=\"{status}\">"
            "<td class=\"cap-name\"><a href=\"capabilities/{slug}.html\">{name}</a><br/><code class=\"cap-key\">{key}</code></td>"
            "<td>{cat}</td><td><span class=\"edition-chip {ed_lower}\">{ed}</span></td>"
            "<td>{badge}</td>"
            "<td>{entry}/{tests}</td>"
            "<td>{sdks}</td>"
            "<td>{samples}</td>"
            "<td>{gaps}</td>"
            "</tr>".format(
                key=esc(cap["key"]),
                cat=esc(cap["category"]),
                ed=esc(cap["edition"]),
                ed_lower=esc(cap["edition"].lower()),
                status=esc(status),
                slug=slug(cap["key"]),
                name=esc(cap["displayName"]),
                badge=render_badge(status),
                entry=cap.get("entryCount", 0),
                tests=cap.get("provingTestCount", 0),
                sdks=sdk_summary,
                samples=sample_count,
                gaps=gap_count,
            )
        )

    total = len(caps)
    counts_by_status: dict[str, int] = {}
    for cap in caps:
        s = capability_status(cap)
        counts_by_status[s] = counts_by_status.get(s, 0) + 1

    summary_stats = "".join(
        f'<div class="stat"><div class="stat-num">{counts_by_status.get(k, 0)}</div>'
        f'<div class="stat-lbl">{esc(v["label"])}</div></div>'
        for k, v in STATUS_VOCAB.items()
    )

    category_options = "".join(f'<option value="{esc(c)}">{esc(c)}</option>' for c in sorted(by_category))

    body = f"""
<h1>Capability evidence index</h1>
<p class="lead">{total} capabilities, joined from honua-server's canonical capability vocabulary and enriched
with SDK coverage, executable samples, and known gaps. Every row links to a page that terminates
in a raw, independently checkable artifact.</p>

<div class="stats-row">{summary_stats}</div>

<div class="filter-bar">
  <input type="search" id="filter-text" placeholder="Filter by name or key…" aria-label="Filter capabilities by name or key" />
  <select id="filter-category" aria-label="Filter by category">
    <option value="">All categories</option>
    {category_options}
  </select>
  <select id="filter-edition" aria-label="Filter by edition">
    <option value="">All editions</option>
    <option value="Community">Community</option>
    <option value="Pro">Pro</option>
    <option value="Enterprise">Enterprise</option>
  </select>
  <select id="filter-status" aria-label="Filter by evidence status">
    <option value="">All statuses</option>
    <option value="source-backed">Source evaluation — counted evidence</option>
    <option value="source-evaluation">Source evaluation</option>
    <option value="partial">Partial coverage</option>
    <option value="proof-pending">Proof pending</option>
  </select>
</div>

<div class="table-wrap">
<table class="data-table" id="cap-table">
  <caption class="sr-only">All capabilities: category, edition, evidence status, counts, SDK coverage, samples, gaps</caption>
  <thead><tr>
    <th scope="col">Capability</th><th scope="col">Category</th><th scope="col">Edition</th>
    <th scope="col">Evidence</th><th scope="col">Entries/Tests</th><th scope="col">SDKs</th>
    <th scope="col">Samples</th><th scope="col">Gaps</th>
  </tr></thead>
  <tbody>{"".join(rows)}</tbody>
</table>
</div>
<p class="no-results" id="no-results" hidden>No capabilities match the current filters.</p>

<script>
(function () {{
  var text = document.getElementById('filter-text');
  var cat = document.getElementById('filter-category');
  var edition = document.getElementById('filter-edition');
  var status = document.getElementById('filter-status');
  var rows = Array.prototype.slice.call(document.querySelectorAll('#cap-table tbody tr'));
  var noResults = document.getElementById('no-results');

  function apply() {{
    var t = text.value.trim().toLowerCase();
    var visible = 0;
    rows.forEach(function (row) {{
      var matchesText = !t || row.dataset.key.toLowerCase().indexOf(t) !== -1 ||
        row.textContent.toLowerCase().indexOf(t) !== -1;
      var matchesCat = !cat.value || row.dataset.category === cat.value;
      var matchesEd = !edition.value || row.dataset.edition === edition.value;
      var matchesStatus = !status.value || row.dataset.status === status.value;
      var show = matchesText && matchesCat && matchesEd && matchesStatus;
      row.hidden = !show;
      if (show) visible++;
    }});
    noResults.hidden = visible !== 0;
  }}

  [text, cat, edition, status].forEach(function (el) {{ el.addEventListener('input', apply); }});
}})();
</script>
"""
    return body


def render_evidence_table(cap: dict[str, Any]) -> str:
    rows = []
    if cap.get("cite"):
        for entry in cap["cite"]:
            rows.append(
                f"<tr><td>CITE / conformance suite</td><td>{esc(entry.get('suite', ''))}"
                f" ({esc(entry.get('profile', ''))})</td>"
                f"<td>{esc(entry.get('passed', 0))}/{esc(entry.get('total', 0))} ({esc(entry.get('passRate', 0))}%)</td></tr>"
            )
    if cap.get("interop"):
        for entry in cap["interop"]:
            rows.append(
                f"<tr><td>Client interop</td><td>{esc(entry.get('clientLane', ''))} / {esc(entry.get('protocol', ''))}</td>"
                f"<td>certified lane (run dates not yet surfaced by this producer — remaining work, see #3)</td></tr>"
            )
    if cap.get("parity"):
        for entry in cap["parity"]:
            rows.append(
                f"<tr><td>Esri GeoServices REST parity</td><td>{esc(entry.get('displayName', entry.get('serviceId', '')))}</td>"
                f"<td>{esc(entry.get('parity', ''))}</td></tr>"
            )
    if cap.get("esriAssess"):
        rows.append(
            f"<tr><td>Esri migration assessment</td><td>assessKey(s)</td><td>{esc(', '.join(cap['esriAssess']))}</td></tr>"
        )
    if cap.get("geobench"):
        rows.append(
            f"<tr><td>Geobench scenario(s)</td><td>{esc(', '.join(cap['geobench']))}</td>"
            f"<td>scenario registered (p95 numbers not yet surfaced by this producer — remaining work, see #3)</td></tr>"
        )
    if cap.get("entryCount", 0) or cap.get("provingTestCount", 0):
        maturity = ", ".join(f"{k}: {v}" for k, v in (cap.get("maturity") or {}).items()) or "—"
        rows.append(
            f"<tr><td>Route entries &amp; proving tests</td><td>{esc(cap['entryCount'])} route entr"
            f"{'y' if cap['entryCount'] == 1 else 'ies'}</td>"
            f"<td>{esc(cap['provingTestCount'])} proving tests ({esc(maturity)})</td></tr>"
        )
    if cap.get("noSurface"):
        ns = cap["noSurface"]
        rows.append(
            f"<tr><td>No distinct route</td><td>{esc(ns.get('reasonCode', ''))}</td><td>{esc(ns.get('reason', ''))}</td></tr>"
        )
    if not rows:
        return '<p class="none">No evidence entries published for this capability yet.</p>'
    return (
        '<div class="table-wrap"><table class="data-table">'
        '<caption class="sr-only">Evidence by type</caption>'
        "<thead><tr><th scope=\"col\">Evidence type</th><th scope=\"col\">Detail</th><th scope=\"col\">Result</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )


def render_sdk_table(cap: dict[str, Any]) -> str:
    sdk_names = {"js": "honua-sdk-js", "dotnet": "honua-sdk-dotnet", "python": "honua-sdk-python"}
    rows = []
    for sdk, repo_name in sdk_names.items():
        entry = cap["sdks"].get(sdk, {"status": "not-covered"})
        status = entry.get("status", "not-covered")
        badge_color = sdk_status_badge(status)
        entrypoints = ", ".join(entry.get("entrypoints", [])[:4]) or "—"
        note = entry.get("note", "")
        rows.append(
            f"<tr><td><a href=\"https://github.com/honua-io/{repo_name}\" target=\"_blank\" rel=\"noopener noreferrer\">{esc(repo_name)}</a></td>"
            f"<td><span class=\"evidence-badge {badge_color}\">{esc(status)}</span></td>"
            f"<td>{esc(entrypoints)}</td>"
            f"<td>{esc(note) if note else '—'}</td></tr>"
        )
    return (
        '<div class="table-wrap"><table class="data-table">'
        '<caption class="sr-only">SDK coverage</caption>'
        "<thead><tr><th scope=\"col\">SDK</th><th scope=\"col\">Status</th><th scope=\"col\">Entry points</th><th scope=\"col\">Note</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )


def render_samples_table(cap: dict[str, Any]) -> str:
    samples = cap.get("samples", [])
    if not samples:
        return '<p class="none">No executable sample published for this capability yet.</p>'
    rows = []
    for s in samples:
        last_run = s.get("lastRun") or {}
        outcome = last_run.get("outcome", "unknown")
        rows.append(
            f"<tr><td><a href=\"{esc(s.get('url', '#'))}\" target=\"_blank\" rel=\"noopener noreferrer\">{esc(s.get('title', s.get('id', '')))}</a></td>"
            f"<td>{esc(', '.join(s.get('sdks', [])))}</td><td>{esc(s.get('edition', ''))}</td>"
            f"<td>{esc(outcome)} (server {esc(last_run.get('serverVersion', '?'))}, {esc(last_run.get('at', 'unknown date'))})</td></tr>"
        )
    return (
        '<div class="table-wrap"><table class="data-table">'
        '<caption class="sr-only">Executable samples</caption>'
        "<thead><tr><th scope=\"col\">Sample</th><th scope=\"col\">SDK lane</th><th scope=\"col\">Edition</th><th scope=\"col\">Last run</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )


def render_gaps(cap: dict[str, Any]) -> str:
    issues = cap.get("openIssues", {})
    refs = issues.get("refs", [])
    if not refs:
        return '<p class="none">No open honua-server issues tagged for this capability’s category.</p>'
    note = (
        '<p class="note">Gaps are currently attached at the <strong>category</strong> level '
        f'(<code>{esc(issues.get("label", ""))}</code> label), not the individual capability key '
        "— finer-grained per-capability mapping is remaining work (honua-io/honua-evidence#5).</p>"
    )
    items = "".join(
        f'<li><a href="{esc(ref["url"])}" target="_blank" rel="noopener noreferrer">#{esc(ref["number"])}</a> {esc(ref["title"])}</li>'
        for ref in refs
    )
    return note + f'<ul class="gaps-list">{items}</ul>'


