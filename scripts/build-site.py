def write_domain_files(site_dir):
    (site_dir / "CNAME").write_text("evidence.honua.io\n", encoding="utf-8")
    (site_dir / ".nojekyll").write_text("", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_SITE_DIR)
    args = parser.parse_args()

    if not args.input.exists():
        print(f"::error::{args.input} does not exist; run scripts/aggregate.py first.")
        return 1

    matrix = json.loads(args.input.read_text(encoding="utf-8"))
    generated_at = matrix.get("generatedAt", "unknown")

    if args.output.exists():
        shutil.rmtree(args.output)
    (args.output / "capabilities").mkdir(parents=True, exist_ok=True)
    (args.output / "data").mkdir(parents=True, exist_ok=True)

    (args.output / "styles.css").write_text(CSS.strip() + "\n", encoding="utf-8")
    shutil.copyfile(args.input, args.output / "data" / "capability-matrix.v1.json")

    index_body = render_index(matrix)
    index_html = render_page(
        title="honua-evidence — capability evidence index",
        description="Browsable index of Honua's capability evidence: entry counts, proving tests, CITE conformance, SDK coverage, executable samples, and known gaps, every claim linked to a raw artifact.",
        body=index_body,
        depth=0,
        generated_at=generated_at,
    )
    (args.output / "index.html").write_text(index_html, encoding="utf-8")

    (args.output / "freshness.html").write_text(
        render_freshness_page(matrix, generated_at), encoding="utf-8"
    )

    for cap in matrix["capabilities"]:
        page = render_capability_page(cap, matrix, generated_at)
        (args.output / "capabilities" / f"{slug(cap['key'])}.html").write_text(page, encoding="utf-8")

    page_count = 2 + len(matrix["capabilities"])  # index + freshness + one per capability
    write_domain_files(args.output)
    print(f"Built {page_count} pages ({len(matrix['capabilities'])} capabilities) into {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
