#!/usr/bin/env python3
"""Render data/capability-matrix.v1.json into a static evidence site
(honua-io/honua-evidence#2, core deliverable).

Zero-dependency: Python standard library only (json, html, pathlib). Takes
no network access -- it renders whatever aggregate.py already wrote to
data/capability-matrix.v1.json. Run aggregate.py first.

Output: site/
  index.html                        all capabilities, filterable, receipts-first
  capabilities/<key-with-dashes>.html  one L2 page per capability
  data/capability-matrix.v1.json    JSON download (copy of the aggregate)
  freshness.html                    per-producer freshness ledger
  styles.css                        shared, plain, print-friendly

Status badge vocabulary is reused verbatim from honua-site's evidence pages
(data/capabilities.v1.json's statusVocabulary in honua-io/honua-site) so a
customer who has seen one recognizes the other:

  source-backed     green  "Source evaluation — counted evidence"
  source-evaluation  green  "Source evaluation"
  partial            amber  "Partial coverage"
  proof-pending      gray   "Proof pending"
"""
from __future__ import annotations

import argparse
import html
import json
import shutil
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = REPO_ROOT / "data" / "capability-matrix.v1.json"
DEFAULT_SITE_DIR = REPO_ROOT / "site"

STATUS_VOCAB = {
    "source-backed": {"badge": "green", "label": "Source evaluation — counted evidence"},
    "source-evaluation": {"badge": "green", "label": "Source evaluation"},
    "partial": {"badge": "amber", "label": "Partial coverage"},
    "proof-pending": {"badge": "gray", "label": "Proof pending"},
}

FRESHNESS_LABEL = {"fresh": "green", "stale": "amber", "missing": "gray"}

SOURCE_REPO_LINKS = {
    "server-keys": "https://github.com/honua-io/honua-server/blob/trunk/docs/gis/data/capability-keys.v1.json",
    "server-matrix": "https://github.com/honua-io/honua-server/blob/trunk/docs/gis/data/capability-matrix.v1.json",
    "sdk-js": "https://github.com/honua-io/honua-sdk-js/blob/trunk/config/sdk-coverage.v1.json",
    "sdk-dotnet": "https://github.com/honua-io/honua-sdk-dotnet/blob/trunk/contracts/sdk-coverage.v1.json",
    "sdk-python": "https://github.com/honua-io/honua-sdk-python/blob/trunk/compatibility/sdk-coverage.v1.json",
    "samples": "https://github.com/honua-io/honua-samples/actions/workflows/run-samples.yml",
    "open-issues": "https://github.com/honua-io/honua-server/issues?q=is%3Aopen+label%3Acap%2F%2A",
}


def esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def slug(key: str) -> str:
    return key.replace(".", "-")


def capability_status(cap: dict[str, Any]) -> str:
    if cap.get("entryCount", 0) > 0 and cap.get("provingTestCount", 0) > 0:
        return "source-backed"
    if cap.get("entryCount", 0) > 0:
        return "source-evaluation"
    if cap.get("noSurface") is not None:
        return "partial"
    return "proof-pending"


def sdk_status_badge(status: str | None) -> str:
    return {"covered": "green", "partial": "amber", "not-covered": "gray"}.get(status or "not-covered", "gray")


